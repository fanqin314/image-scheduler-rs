// ============================================================
// types.rs - 公共数据结构定义
//
// 本文件定义了整个系统各模块之间传递的数据类型。
// 所有模块（features、evaluator、visualization、handlers）
// 都依赖这些结构体，保持数据格式统一。
// ============================================================

use serde::Serialize;
use std::collections::HashMap;

// ------------------------------------------------------------
// 1. 特征响应结构体
// 用途：handlers 返回给前端 JSON 时使用的 7 维特征数据
// 对应关系：与前端 index.html 中 featureNames 的顺序一一对应
// ------------------------------------------------------------
#[derive(Serialize)]
pub struct FeatureResponse {
    /// 香农熵 (Shannon Entropy)
    /// 取值范围: 0.0 ~ 8.0 (对于8位灰度图)
    /// 物理意义: 灰度分布的随机性
    ///   - 0.0 : 全黑或全白（单一灰度值）
    ///   - ~8.0 : 像素灰度完全随机分布（如雪花噪点）
    /// 用途: 区分"纯色背景"和"内容丰富"的图片
    pub entropy: f64,

    /// 全局边缘占比 (Global Edge Ratio)
    /// 取值范围: 0.0 ~ 1.0
    /// 物理意义: 经过 Sobel 边缘检测后，梯度 > 15 的像素占总像素的比例
    ///   - 0.0 : 无边缘（纯色/严重模糊）
    ///   - 1.0 : 全是边缘（理论值，实际不会达到）
    /// 用途: 判断画面是否有"有效内容"——这是最核心的调度指标之一
    pub edge_ratio: f64,

    /// 平均亮度 (Brightness)
    /// 取值范围: 0.0 ~ 1.0 (归一化，0=纯黑，1=纯白)
    /// 物理意义: 全图所有像素灰度值的平均值 / 255
    /// 用途: 配合亮度惩罚机制，过滤过曝/欠曝的"废图"
    pub brightness: f64,

    /// 局部峰值边缘密度 (Local Peak)
    /// 取值范围: 0.0 ~ 1.0
    /// 物理意义: 在 128x128 缩略图上，用 32x32 滑动窗口（步长16）扫描，
    ///          所有窗口中边缘密度最高的那个窗口的密度值
    /// 用途: 捕捉"全局很空但局部有料"的场景（如白墙上的一个钉子）
    ///       这是区分"空旷巡航"和"前方有车"的关键特征
    pub local_peak: f64,

    /// 局部离散度 (Local Variance)
    /// 取值范围: 0.0 ~ ∞（实际通常 0.0 ~ 0.5）
    /// 物理意义: 所有滑动窗口边缘密度的方差
    ///   - 接近 0.0 : 画面边缘分布均匀（噪点图 或 均匀纹理）
    ///   - 较大值 : 画面疏密有致（有主体有背景）
    /// 用途: 区分"均匀噪点"和"真实有内容的场景"
    pub local_variance: f64,

    /// 下半区优势比 (Lower Advantage)
    /// 取值范围: 0.0 ~ ∞（实际通常 0.5 ~ 3.0）
    /// 物理意义: 128x128 图中，下半区（y>=64）的边缘数量 / 上半区（y<64）的边缘数量
    ///   - < 1.0 : 天空/远景更丰富
    ///   - > 1.0 : 路面/近景更丰富（车行场景的典型特征）
    /// 用途: 车行场景专用——下半区通常是路面和前方车辆，上半区是天空
    pub lower_advantage: f64,

    /// 帧间运动幅度 (Motion Magnitude)
    /// 取值范围: 0.0 ~ 255.0
    /// 物理意义: 当前帧与上一帧的像素差绝对值的平均值
    ///   - 0.0 : 静止画面（或单张图片）
    ///   - 越大 : 画面变化越剧烈（急刹、变道、前车切入）
    /// 用途: 风险事件的"触发器"——运动大时，即使画面熵值低也强制送云端
    /// 注意: 当前单图模式恒为 0.0，视频流模式才真正生效
    pub motion: f64,
}

// ------------------------------------------------------------
// 2. 价值评估响应结构体
// 用途：handlers 返回给前端 JSON 时的决策结果
// ------------------------------------------------------------
#[derive(Serialize)]
pub struct EvaluationResponse {
    /// 价值分 (Value Score)
    /// 取值范围: 0.0 ~ 1.0
    /// 物理意义: 综合 7 维特征加权计算出的"画面价值"
    ///   - 0.0 ~ 0.4 : DROP（丢弃/轻量处理）
    ///   - 0.4 ~ 0.7 : LOCAL（本地推理）
    ///   - 0.7 ~ 1.0 : CLOUD（云端推理）
    /// 计算公式: 见 evaluator.rs
    pub score: f64,

    /// 调度决策动作 (Scheduling Action)
    /// 取值范围: "CLOUD" | "LOCAL" | "DROP"
    ///   - CLOUD : 此图应发送云端 GPU 服务（高价值/高风险）
    ///   - LOCAL : 此图应本地轻量模型处理（中等价值）
    ///   - DROP  : 此图应丢弃或极简处理（低价值/废图）
    pub action: String,
}

// ------------------------------------------------------------
// 3. 完整上传响应结构体
// 用途：handlers 的 /upload 接口返回给前端的完整 JSON
// 结构：特征数据 + 决策结果 + 两张图片的 Base64
// ------------------------------------------------------------
#[derive(Serialize)]
pub struct UploadResponse {
    /// 7维特征向量
    pub features: FeatureResponse,

    /// 价值评估结果（分数 + 决策动作）
    pub evaluation: EvaluationResponse,

    /// 原图缩略图 (Base64 编码的 JPEG)
    /// 用于前端显示原图缩略
    pub original_image: String,

    /// 可视化标注图 (Base64 编码的 JPEG)
    /// 包含：边缘叠加层 + 灰色网格 + 绿色峰值窗口 + 黄色下半区线
    pub visualized_image: String,
}

// ------------------------------------------------------------
// 4. 特征映射类型别名
// 用途：features.rs 模块内部使用，用 HashMap 传递特征数据
//       方便动态增删特征（不修改结构体定义）
// 与 FeatureResponse 的关系：
//   - FeatureMap : 模块内部传递（灵活）
//   - FeatureResponse : 对外输出（固定格式）
// ------------------------------------------------------------
pub type FeatureMap = HashMap<String, f64>;